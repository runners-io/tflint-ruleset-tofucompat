package compat

import (
	"fmt"
	"os"
	"strings"
	"testing"
)

// The rule reference on the customer docs page is GENERATED from the rule
// table, so its claims cannot drift from what the rules do (CLAUDE.md §14):
//
//	TOFUCOMPAT_WRITE_DOCS=../../../apps/web/content/docs/infrastructure-runs/opentofu-compatibility.md \
//	  go test ./compat/ -run TestRuleReference
//
// rewrites the text between the two markers below. apps/web's
// the-opentofu-compatibility-page-agrees-with-the-code.test.ts fails when the
// page and rules.go disagree, so forgetting to regenerate is caught there.
const (
	refBegin = "<!-- BEGIN rule reference: generated by tofucompat/compat/docs_test.go -->"
	refEnd   = "<!-- END rule reference -->"
)

func ruleReference() string {
	var b strings.Builder
	b.WriteString(refBegin + "\n")
	for _, r := range Rules {
		fmt.Fprintf(&b, "\n### `%s`\n\n", r.ID)
		since := "No OpenTofu release supports it yet."
		if r.OpenTofuSince != "" {
			since = fmt.Sprintf("OpenTofu supports it from **%s**, so the rule applies to earlier versions only.", strings.TrimSuffix(r.OpenTofuSince, ".0"))
		}
		sev := "Error: OpenTofu refuses the configuration."
		if r.Severity == Warning {
			sev = "Warning: the configuration runs, but not the way it does under Terraform."
		}
		fmt.Fprintf(&b, "%s, added in Terraform %s. %s %s\n\n", upperFirst(r.Construct), r.TerraformSince, since, sev)
		fmt.Fprintf(&b, "%s\n\n", r.Message)
		fmt.Fprintf(&b, "**Fix:** %s\n", r.Remedy)
		if r.HasFix() {
			fmt.Fprintf(&b, "\n**Mechanical fix:** %s\n", r.FixDescription)
		}
	}
	b.WriteString("\n" + refEnd)
	return b.String()
}

func upperFirst(s string) string {
	if s == "" || s[0] == '`' {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func TestRuleReference(t *testing.T) {
	ref := ruleReference()
	for _, r := range Rules {
		if !strings.Contains(ref, "### `"+r.ID+"`") {
			t.Errorf("no heading for %s", r.ID)
		}
	}
	path := os.Getenv("TOFUCOMPAT_WRITE_DOCS")
	if path == "" {
		return
	}
	page, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	s := string(page)
	i, j := strings.Index(s, refBegin), strings.Index(s, refEnd)
	if i < 0 || j < i {
		t.Fatalf("%s has no rule reference markers", path)
	}
	out := s[:i] + ref + s[j+len(refEnd):]
	if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
		t.Fatal(err)
	}
}
